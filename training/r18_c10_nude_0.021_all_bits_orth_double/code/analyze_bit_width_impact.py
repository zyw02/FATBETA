#!/usr/bin/env python
"""分析位宽对故障注入影响的原因"""
import torch
import numpy as np

print("="*80)
print("分析：为什么 6-bit 比 2-bit 对故障注入更鲁棒？")
print("="*80)

# 1. 量化精度差异
print("\n1. 量化精度差异：")
print("-" * 80)
print("2-bit 量化：")
print("  - 权重值范围：[-2, 1] (signed) 或 [0, 3] (unsigned)")
print("  - 可表示的离散值数量：4 个")
print("  - 量化步长：较大，量化误差大")
print("  - 单个 bit 翻转的影响：")
print("    * 例如：权重值 2 (二进制 10) → bit 翻转 → 3 (二进制 11)")
print("    * 相对变化：50% (从 2 到 3)")
print("    * 影响：非常大！")

print("\n6-bit 量化：")
print("  - 权重值范围：[-32, 31] (signed) 或 [0, 63] (unsigned)")
print("  - 可表示的离散值数量：64 个")
print("  - 量化步长：较小，量化误差小")
print("  - 单个 bit 翻转的影响：")
print("    * 例如：权重值 32 (二进制 100000) → bit 翻转 → 33 (二进制 100001)")
print("    * 相对变化：3.1% (从 32 到 33)")
print("    * 影响：相对较小")

# 2. 故障注入的影响
print("\n2. 故障注入的影响（相同 BER 下）：")
print("-" * 80)
print("假设 BER = 1e-1 (10% 的 bit 会被翻转)")

print("\n2-bit 情况：")
print("  - 每个权重只有 2 个 bit")
print("  - 10% 的 bit 翻转意味着：")
print("    * 平均每个权重有 0.2 个 bit 被翻转")
print("    * 由于只有 2 个 bit，这意味着约 10% 的权重会完全改变")
print("  - 影响：权重值可能从 0 变成 2，或从 2 变成 0")
print("  - 结果：模型行为发生剧烈变化")

print("\n6-bit 情况：")
print("  - 每个权重有 6 个 bit")
print("  - 10% 的 bit 翻转意味着：")
print("    * 平均每个权重有 0.6 个 bit 被翻转")
print("    * 由于有 6 个 bit，大多数权重只会改变 1 个 bit")
print("  - 影响：权重值可能从 32 变成 33，或从 32 变成 48（如果高位翻转）")
print("  - 结果：模型行为变化相对较小")

# 3. 量化噪声累积
print("\n3. 量化噪声 vs 故障噪声：")
print("-" * 80)
print("2-bit 量化：")
print("  - 量化噪声：大（只有 4 个离散值）")
print("  - 故障噪声：大（bit 翻转影响大）")
print("  - 总噪声 = 量化噪声 + 故障噪声")
print("  - 结果：噪声累积严重，模型性能急剧下降")

print("\n6-bit 量化：")
print("  - 量化噪声：小（有 64 个离散值）")
print("  - 故障噪声：中等（bit 翻转影响相对较小）")
print("  - 总噪声 = 量化噪声 + 故障噪声")
print("  - 结果：噪声累积较小，模型性能下降较少")

# 4. 数值示例
print("\n4. 数值示例：")
print("-" * 80)
print("假设原始权重值 = 0.5（浮点数）")

print("\n2-bit 量化（假设 scale=0.5）：")
print("  - 量化后：round(0.5/0.5) = 1 → 1 * 0.5 = 0.5")
print("  - 如果 bit 翻转：1 (01) → 2 (10) → 2 * 0.5 = 1.0")
print("  - 误差：|1.0 - 0.5| = 0.5 (100% 相对误差)")

print("\n6-bit 量化（假设 scale=0.1）：")
print("  - 量化后：round(0.5/0.1) = 5 → 5 * 0.1 = 0.5")
print("  - 如果 bit 翻转：5 (000101) → 4 (000100) → 4 * 0.1 = 0.4")
print("  - 误差：|0.4 - 0.5| = 0.1 (20% 相对误差)")

# 5. 模型容量
print("\n5. 模型容量和冗余：")
print("-" * 80)
print("6-bit 模型：")
print("  - 能表示更多的权重值组合")
print("  - 模型容量更大，有更多冗余")
print("  - 即使部分权重被故障影响，其他权重可以补偿")
print("  - 结果：对故障的容忍度更高")

print("\n2-bit 模型：")
print("  - 只能表示很少的权重值组合")
print("  - 模型容量小，冗余少")
print("  - 每个权重都很关键，故障影响难以补偿")
print("  - 结果：对故障的容忍度低")

print("\n" + "="*80)
print("总结：")
print("="*80)
print("1. 量化精度：6-bit 的量化误差远小于 2-bit")
print("2. 故障影响：相同 BER 下，6-bit 的单个 bit 翻转影响更小")
print("3. 噪声累积：2-bit 的量化噪声和故障噪声都很大，累积效应严重")
print("4. 模型容量：6-bit 模型有更多冗余，对故障的容忍度更高")
print("5. 数值稳定性：6-bit 的权重值范围更大，bit 翻转的相对影响更小")
print("="*80)



